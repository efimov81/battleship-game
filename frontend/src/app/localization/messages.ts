export const messages = { en, ru };
export type Language = keyof typeof messages;

const botLabels = new Map<string, MessageKey>([
  ['random', 'beginner'],
  ['medium', 'medium'],
  ['hard', 'hard'],
]);

export function botLabel(dictionary: Messages, id: string): string {
  return dictionary[botLabels.get(id) ?? 'unknownDifficulty'];
}

const apiErrors = new Map<string, MessageKey>([
  ['UNKNOWN_BOT', 'unknownDifficulty'],
  ['NOT_FOUND', 'gameNotFound'],
  ['WRONG_PHASE', 'wrongPhase'],
  ['INVALID_FLEET', 'invalidFleet'],
  ['WRONG_TURN', 'wrongTurn'],
  ['BAD_COORDINATE', 'badCoordinate'],
  ['REPEAT_SHOT', 'repeatShot'],
  ['STALE_GAME', 'staleGame'],
  ['NO_LEGAL_MOVES', 'noLegalMoves'],
  ['INTERNAL_ERROR', 'serverError'],
]);

export function errorMessageKey(code: unknown, fallback: MessageKey): MessageKey {
  return typeof code === 'string' ? (apiErrors.get(code) ?? fallback) : fallback;
}
